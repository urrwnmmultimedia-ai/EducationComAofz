| 2. รวบรวมข้อมูล | ค้นวิธีแยกขยะของโรงเรียนอื่น ดูคลิปถังขยะแยกประเภท ระดมความคิดได้ 5 แนวคิด |
| 3. ออกแบบ | เลือก "ถังแยก 3 ช่อง + ป้ายรูปภาพใหญ่ + ช่องเทน้ำ" ร่างภาพพร้อมขนาด |
