## เริ่มจากมือถือในมือเรา
วันนี้เราใช้มือถือทำอะไรไปแล้วบ้าง? ดูคลิปสั้น เล่นเกมออนไลน์ วิดีโอคอลกับเพื่อน สแกนจ่ายเงิน ดูตำแหน่งรถเมล์…
ทุกอย่างนี้ต้องพึ่ง **เครือข่ายไร้สาย** ที่ส่งข้อมูลผ่านคลื่นวิทยุ

