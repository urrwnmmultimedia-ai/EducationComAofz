-- 024 แก้: ตอนเพิ่ม students.login_count (023) ทุกคนเริ่มที่ 0
--   => นักเรียนที่ใช้งานมานานแล้ว เข้าสู่ระบบครั้งแรกหลังอัปเดตถูกนับเป็น "ครั้งแรก" จึงไม่ได้หน้าต่างทักทาย
--   นักเรียนที่เคยเข้าสู่ระบบแล้ว (bound_auth_uid ไม่ว่าง — ออกจากระบบไม่ล้างค่านี้) ตั้งเป็น 1
--   คนที่ยังไม่เคยเข้าเลยคงเป็น 0 (ครั้งแรกจริงยังไม่ทักทาย) · รันซ้ำได้ ไม่กระทบคนที่นับไปแล้ว
-- =============================================================

update public.students
set login_count = 1
where login_count = 0 and bound_auth_uid is not null;
